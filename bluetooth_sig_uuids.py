def _extract_short_uuid(uuid: str) -> str:
    """Return the canonical 16-bit key used for SIG table lookups."""
    uuid = uuid.strip().lower()
    # Standard 128-bit SIG UUID: 0000XXXX-0000-1000-8000-00805f9b34fb
    if len(uuid) == 36 and uuid.endswith("-0000-1000-8000-00805f9b34fb"):
        return uuid[4:8]
    # Already short (4 or 8 hex chars)
    if len(uuid) in (4, 8):
        return uuid[-4:]
    return uuid


def lookup_service(uuid: str) -> str | None:
    return GATT_SERVICES.get(_extract_short_uuid(uuid))


def lookup_characteristic(uuid: str) -> str | None:
    return GATT_CHARACTERISTICS.get(_extract_short_uuid(uuid))


def lookup_descriptor(uuid: str) -> str | None:
    return GATT_DESCRIPTORS.get(_extract_short_uuid(uuid))


def lookup_any(uuid: str) -> str | None:
    """Look up a UUID across services, characteristics, and descriptors."""
    short = _extract_short_uuid(uuid)
    return (
        GATT_SERVICES.get(short)
        or GATT_CHARACTERISTICS.get(short)
        or GATT_DESCRIPTORS.get(short)
    )
