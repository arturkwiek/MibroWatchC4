# Helper: normalize any UUID to full 128-bit lowercase string
def normalize_uuid(uuid: str) -> str:
    uuid = uuid.strip().lower()
    # 16-bit short form (4 hex digits)
    if len(uuid) == 4:
        return f"0000{uuid}-0000-1000-8000-00805f9b34fb"
    # 32-bit short form (8 hex digits)
    if len(uuid) == 8:
        return f"{uuid}-0000-1000-8000-00805f9b34fb"
    return uuid


